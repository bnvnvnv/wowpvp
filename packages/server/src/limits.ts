/**
 * 公网硬化的全部资源上限（技术债总账 S1–S3、S5–S6，docs/16 批次三 3.6）。
 *
 * ★★ **这里防的不是作弊，是「量」。** codec/可见性裁剪（M10）挡的是
 *   内容层 —— 假伤害、透视、瞬移；本表挡的是**每条都完全合法、只是
 *   量大/包大/行为怪**的滥用：连上来的不再假设是自己人。
 *
 * ★ 全部集中在一张表：这些数值互相之间有一致性约束（例如限流回填速率
 *   必须显著高于合法客户端的稳态流量），散在各文件里会被单独改坏。
 *   每个值都可被 `ServerOptions` 逐项覆盖 —— 测试把阈值压小，
 *   跑的仍是生产那条判定路径。
 */
export const LIMITS = {
  /**
   * 单条入站消息的字节上限。`ws` 的默认是 **100MiB** —— 一条 50MB 的
   * JSON 在解析瞬间让内存翻倍。合法消息里最大的是 CastRequest（<300B），
   * 16KB 已经放了 50 倍余量；超限由 ws 以 1009 关闭连接。
   */
  MAX_PAYLOAD_BYTES: 16 * 1024,

  /**
   * 出站缓冲（`bufferedAmount`）超过这个值就 terminate —— 慢读者防线。
   * 客户端故意不读（或网络黑洞）时，服务器每 50ms 一份快照会把发送缓冲
   * 堆到内存耗尽。快照流约 100KB/s：1MB ≈ 落后 10 秒，这个连接救不回来了，
   * 断开让他走重连路径（令牌整局有效，回来毫发无损 —— 偏差 #14）。
   */
  BACKPRESSURE_BYTES: 1024 * 1024,

  /** 同时在线连接数上限。超出的在握手后立即以 1013（稍后再试）关闭 */
  MAX_CONNECTIONS: 256,

  /** 同时存在的房间数上限。满了拒绝**新建**（加入既有房间不受影响） */
  MAX_ROOMS: 64,

  /**
   * 单房间成员总数上限（含观战席）。12v12 = 24 名选手，留 8 个观战位。
   * ★ 这是**服务器资源上限**不是游戏规则：3.2「观战席不设限」的规则语义
   *   不动（sim 的 joinRoom 仍然不限），每个观战者每 tick 都要一份
   *   完整快照构建 + 序列化，无上限就是免费的放大器。
   */
  MAX_ROOM_MEMBERS: 32,

  /**
   * 入站消息令牌桶：容量（突发额度）与每秒回填。
   *
   * 合法客户端的稳态流量：每 tick 一条 Input = 20/s，加上人手点击的
   * 命令流 ≤10/s（InputManager 过滤了按键重复，按住 Tab 不会连发）——
   * 稳态 ~30/s 封顶。回填 30/s 正好覆盖，容量 40 吃掉进房/重连的突发
   * （四连发 + 补一秒积压）。1000 条/s 的灌注 ≈ 97% 被丢弃。
   */
  RATE_CAPACITY: 40,
  RATE_REFILL_PER_SEC: 30,

  /**
   * 累计丢弃这么多条后直接断开 —— 短暂超速（网络抖动后的补发风暴）只丢
   * 不断，持续灌注（500 条 ≈ 正常玩家 17 秒的全部流量在几百毫秒内砸来）
   * 是脚本，不是人。断开走与心跳超时同一条 close → 接管路径。
   */
  RATE_DISCONNECT_AFTER_DROPPED: 500,

  /**
   * 每玩家每 tick 进入 MatchLoop 的战斗指令数上限（S1 的第二道防线）。
   * 令牌桶按秒算，这里按 tick 算：即便有消息种类绕过了桶（将来的疏忽），
   * 一 tick 也做不了 1000 次 TabTarget 全实体排序。合法玩家一 tick
   * 至多两三条（50ms 里点不出更多）。
   */
  COMMANDS_PER_TICK_MAX: 16,
} as const;
