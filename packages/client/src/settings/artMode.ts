/**
 * M12：外部美术素材的总开关（`?art=off`）。
 *
 * ★★ **为什么需要它，而不是「素材缺失时自动回落」就够了：**
 *
 *   自动回落已经有了（模型/环境/图标/音频每一层都有），它管的是
 *   「文件不在」。这个开关管的是**另一件事**：文件在，但我不想加载。
 *
 *   ⚠️ 直接的动因是一次实测：接入美术后，`--use-gl=swiftshader`
 *   （M1–M8 验收脚本用的软件渲染）下帧率从 **21 掉到 4** ——
 *   PBR 材质 × IBL × 四个蒙皮角色对软件光栅化器是压倒性的。
 *   那 106 项验收验的是移动、镜头、目标、打断，**没有一条与美术有关**，
 *   却会因为跑不动而集体超时。这不是缺陷，是测量环境的伪影。
 *
 *   ★ 所以分工是明确的：
 *     · `verify:m1`–`m9` 用 `?art=off` 跑 —— 它们验的是**规则接线**，
 *       与 M0–M11 完全同一条路径，结论可以直接与历史对比
 *     · `verify:m12` 用 `?art=on`（默认）跑 —— 它专门验**美术层本身**，
 *       以及美术引入后 #10 / #48 是否仍然成立
 *
 *   ⚠️ **不要**把这个开关用来「优化」真实玩家的画面 —— 那是 F2 画质档位
 *   （17.1）的职责，而画质档位受验收 #48 的类型约束保护。
 *   这个开关不受那套约束，因为它关掉的是**全部**外部素材，
 *   回落到的是 M11 那个已经通过全部 52 条验收的程序化表现。
 */

/** `?art=off` 时返回 false。默认（含参数缺失、参数写错）一律返回 true */
export const artEnabled = (search: string = globalThis.location?.search ?? ''): boolean =>
  new URLSearchParams(search).get('art') !== 'off';
