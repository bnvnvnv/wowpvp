/**
 * 假人布置。**验收用一套，教学用一套。**
 *
 * ★★ **这两套的约束天生冲突，不该共用一份坐标。**
 *
 *   · **验收**要的是「钉在已知坐标上」—— 二十多支脚本靠固定位置做镜像走位、
 *     算距离、找目标。挪一米就有断言要改。
 *   · **教学**要的是「为这一课服务」—— 第一环教走路，正前方就不能站人。
 *
 *   此前两者共用 `CombatDirector` 里写死的三行坐标，于是上一轮的软推开修复
 *   （角色不再互相重叠）让教学第一环**当场卡死**：新玩家按下 W，被正前方
 *   2.6 米的战士假人顶住，走不满 5 米。而这个问题从任何一侧都看不见 ——
 *   教学那条「正前方 5 米内不能站人」的前提不写在任何地方，
 *   验收也不知道自己的坐标被别人当成了教学舞台。
 *
 * ★ 分开的只有**布置**（数据）。假人的行为、决策（`botController`）、
 *   渲染、HUD 全部照旧共享 —— 那些复制一份就是「同一件事两份实现」，
 *   这个仓库在护盾判据上已经吃过一次亏（联网侧四态少画两态）。
 */

import type { Vec3 } from '@wowpvp/shared';

/** 一个假人的位置（相对玩家出生点）与名字 */
export interface DummySpot {
  /** 职业。★ 用字符串而不是 ClassDef —— 布置是数据，不该 import 八个职业 */
  classId: 'warrior' | 'priest' | 'mage';
  /** 相对玩家出生点的偏移 */
  offset: Vec3;
  name: string;
}

/**
 * 验收用布置。**坐标逐字等于历史值** —— 这是 M1–M16 两百多项验收的初始条件，
 * 改一个数字就要重跑全部脚本。
 *
 * 三个假人各自演示反制链的一环：
 *   战士 —— 用拳击打断**你的**读条，让你体会被打断与假读条博弈
 *   牧师 —— 反复读条治疗，给你练打断与学派锁定
 *   法师 —— 读条法术，同时也是唯一会对你造成伤害的假人
 *
 * ★ 战士刻意放在出生点**正前方** 2.6 米：拳击是 3 米近战技能，
 *   放远了它永远够不到你，7.5 的假读条博弈就演示不出来。
 */
export const VERIFY_DUMMIES: readonly DummySpot[] = [
  { classId: 'warrior', offset: { x: 0, y: 0, z: -2.6 }, name: '假人·战士' },
  { classId: 'priest', offset: { x: 6, y: 0, z: -18 }, name: '假人·牧师' },
  { classId: 'mage', offset: { x: 0, y: 0, z: -26 }, name: '假人·法师' },
];

